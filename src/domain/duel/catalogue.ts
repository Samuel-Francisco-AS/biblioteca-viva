const effect = (
  definitionId: DuelEffect["definitionId"],
  value: number,
  target: DuelEffect["target"],
  duration: DuelEffect["duration"] = "permanent",
): DuelEffect => ({ definitionId, value, target, duration });
const play = (...effects: DuelEffect[]): DuelAbility[] => [
  { id: "manifestar", trigger: "play", cost: 0, effects },
];
const activate = (cost: number, ...effects: DuelEffect[]): DuelAbility[] => [
  { id: "canalizar", trigger: "activate", cost, effects },
];
const start = (...effects: DuelEffect[]): DuelAbility[] => [
  { id: "aurora", trigger: "start", cost: 0, effects },
];
interface Entry {
  slug: string;
  name: string;
  affinity: Affinity;
  kind: CombatDefinition["kind"];
  cost: number;
  attack?: number;
  health?: number;
  keywords?: CombatDefinition["keywords"];
  abilities?: DuelAbility[];
  flavor: string;
  subject: string;
}
const creature = (
  affinity: Affinity,
  slug: string,
  name: string,
  cost: number,
  attack: number,
  health: number,
  flavor: string,
  subject: string,
  abilities: DuelAbility[] = [],
  keywords: CombatDefinition["keywords"] = [],
): Entry => ({
  affinity,
  slug,
  name,
  cost,
  attack,
  health,
  flavor,
  subject,
  kind: "creature",
  abilities,
  keywords,
});
const spell = (
  affinity: Affinity,
  slug: string,
  name: string,
  cost: number,
  flavor: string,
  subject: string,
  abilities: DuelAbility[],
): Entry => ({
  affinity,
  slug,
  name,
  cost,
  flavor,
  subject,
  abilities,
  kind: "spell",
});
const artifact = (
  affinity: Affinity,
  slug: string,
  name: string,
  cost: number,
  flavor: string,
  subject: string,
  abilities: DuelAbility[],
): Entry => ({
  affinity,
  slug,
  name,
  cost,
  flavor,
  subject,
  abilities,
  kind: "artifact",
});
