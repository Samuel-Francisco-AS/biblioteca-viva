export const officialCards: readonly Card[] = officialEntries.map((e) =>
  cardSchema.parse({
    id: `arcane-v1:${e.slug}`,
    revision: 1,
    type: "combat",
    origin: {
      kind: "official",
      packId: CATALOGUE_ID,
      itemId: e.slug,
      version: "1.0.0",
    },
    createdAt: timestamp,
    updatedAt: timestamp,
    archived: false,
    content: {
      type: "combat",
      name: e.name,
      attributes: {},
      effects: [],
      combat: {
        version: 1,
        kind: e.kind,
        affinity: e.affinity,
        cost: e.cost,
        ...(e.kind === "creature" && { attack: e.attack, health: e.health }),
        keywords: e.keywords ?? [],
        abilities: e.abilities ?? [],
        flavor: e.flavor,
        artId: e.slug,
      },
    },
  }),
);
const neutralChoices = {
  ruin: ["clock-beetle", "unbinding"],
  knowledge: ["candle-fox", "wayfarer-lantern"],
  bloom: ["stone-sentinel", "lost-compass"],
  chaos: ["comet-ray", "quiet-pulse"],
};
export const starterDecks: readonly Deck[] = (
  ["ruin", "knowledge", "bloom", "chaos"] as const
).map((affinity) => {
  const cards = officialEntries
    .filter(
      (e) =>
        e.affinity === affinity || neutralChoices[affinity].includes(e.slug),
    )
    .map((e) => ({ cardId: `arcane-v1:${e.slug}`, revision: 1 }));
  return deckSchema.parse({
    id: `arcane-deck:${affinity}`,
    name: `${traditions[affinity].duelist} · ${traditions[affinity].name}`,
    revision: 1,
    createdAt: timestamp,
    updatedAt: timestamp,
    origin: {
      kind: "official",
      packId: CATALOGUE_ID,
      itemId: affinity,
      version: "1.0.0",
    },
    selection: { kind: "static", cards },
    combat: {
      version: 1,
      affinity,
      mode: "official",
      copies: Object.fromEntries(cards.map((c) => [c.cardId, 2])),
    },
  });
});
